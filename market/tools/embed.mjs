// Builds market/embeds.js: one image fingerprint per film, used by "Match a reference" on the client site.
// Each film's cover (and, for YouTube, three frames from the middle of the film) goes through the same small CLIP image model
// the browser runs on the client's reference video; matching is the cosine between the two.
// Needs @huggingface/transformers next to it:  cd market/tools && npm i @huggingface/transformers@4.3.2 && node embed.mjs
// Re-run after creators.js changes; a film with no fingerprint is ranked last.
import fs from "node:fs";
import { AutoProcessor, CLIPVisionModelWithProjection, RawImage } from "@huggingface/transformers";
const MODEL = "Xenova/mobileclip_s0", DTYPE = "fp32";   // the 8-bit version of this model gives unusable vectors; keep fp32 on both sides
const root = new URL("..", import.meta.url).pathname;
const CREATORS = new Function(fs.readFileSync(root + "creators.js", "utf8") + "; return CREATORS;")();
const keyOf = m => m.yt || m.vm || m.mp4 || m.link;
const imgs = m => m.yt ? ["hqdefault", "hq1", "hq2", "hq3"].map(n => `https://i.ytimg.com/vi/${m.yt}/${n}.jpg`) : m.cover ? [m.cover] : [];
const processor = await AutoProcessor.from_pretrained(MODEL);
const model = await CLIPVisionModelWithProjection.from_pretrained(MODEL, { dtype: DTYPE });
const embed = async url => { const img = await RawImage.read(url); const { image_embeds } = await model(await processor(img)); const v = Array.from(image_embeds.data); const n = Math.hypot(...v); return v.map(x => x / n); };
const seen = new Map(); let miss = 0;
const works = CREATORS.flatMap(c => c.works).filter(w => w[5] && keyOf(w[5]));
for (const [i, w] of works.entries()){
  const k = keyOf(w[5]); if (seen.has(k)) continue;
  const vs = []; for (const u of imgs(w[5])){ try { vs.push(await embed(u)); } catch {} }
  if (!vs.length){ miss++; continue; }
  const mean = vs[0].map((_, j) => vs.reduce((s, v) => s + v[j], 0) / vs.length); const n = Math.hypot(...mean);
  seen.set(k, mean.map(x => x / n));
  if (i % 50 === 0) console.error(i + "/" + works.length);
}
const keys = [...seen.keys()], dim = 512, scale = 400;   // components sit well inside ±0.3; ×400 keeps them in int8
const buf = Buffer.alloc(keys.length * dim);
keys.forEach((k, i) => seen.get(k).forEach((x, j) => buf.writeInt8(Math.max(-127, Math.min(127, Math.round(x * scale))), i * dim + j)));
fs.writeFileSync(root + "embeds.js", `/* Generated by tools/embed.mjs: image fingerprints of ${keys.length} films. Regenerate, don't hand-edit. */\nconst EMBEDS = ${JSON.stringify({ model: MODEL, dtype: DTYPE, dim, keys, data: buf.toString("base64") })};\n`);
console.log("films", keys.length, "missing", miss, "bytes", buf.length);
